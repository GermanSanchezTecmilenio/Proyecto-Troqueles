INSERT INTO clientes (nombre_cliente, razon_social, formato_factura, activo)
SELECT client_name, client_name, TRUE, TRUE
FROM (
  SELECT 'ROSENBERGER' AS client_name
  UNION ALL SELECT 'STABILUS'
  UNION ALL SELECT 'MOLDED FIBERGLASS DE MEXICO S DE RL DE CV'
  UNION ALL SELECT 'EINSA'
) AS legacy_clients
WHERE NOT EXISTS (
  SELECT 1
    FROM clientes
   WHERE UPPER(nombre_cliente) = UPPER(legacy_clients.client_name)
);

